#!/usr/bin/env bash
# Compose the Supplementary latent-space figures from the panels written by
# make_si_latent_figs.py: for experiments 123 and 18, a (latent overlay) above
# b (global maps); for experiment 80 the overlay alone. Each panel is included
# at scale 0.4 = 1/2.5 of its 18 in canvas inside a 183 mm box with a 1 mm
# border, as compose_fig9.sh does, so \includegraphics[width=\textwidth] in the
# SI shows the figure at 183 mm with the house text sizes.
# Usage: ./compose_si_latent.sh [iterations]   (default: "123 18 80");
#        outputs figures/house/latent_space_<it>.pdf (generated .tex kept beside them).
set -euo pipefail
cd "$(dirname "$0")"
ITS="${1:-123 18 80}"
PANELS=figures/house
SCALE=0.4
WIDTH_MM=183
ROWGAP_MM=2

width_mm() { pdfinfo "$1" | awk -v s="$SCALE" '/Page size/ {printf "%.2f", $3 * s * 25.4 / 72}'; }

for it in $ITS; do
  A="$PANELS/si_latent_${it}_a.pdf"; B="$PANELS/si_latent_${it}_b.pdf"
  test -f "$A" || { echo "missing $A (run make_si_latent_figs.py)"; exit 1; }
  TEX="$PANELS/latent_space_${it}.tex"
  wa=$(width_mm "$A"); echo "exp $it: a $wa mm$( [ -f "$B" ] && echo ", b $(width_mm "$B") mm" ) in a $WIDTH_MM mm box"
  {
    echo "% generated by compose_si_latent.sh; do not edit by hand"
    echo '\documentclass[border=1mm]{standalone}'
    echo '\usepackage[T1]{fontenc}'
    echo '\usepackage{helvet}'
    echo '\renewcommand{\familydefault}{\sfdefault}'
    echo '\usepackage{graphicx}'
    echo '\begin{document}'
    echo "\\begin{minipage}[t]{${WIDTH_MM}mm}"
    echo '\setlength{\parindent}{0pt}\setlength{\parskip}{0pt}'
    echo "\\includegraphics[scale=$SCALE]{si_latent_${it}_a.pdf}"
    if [ -f "$B" ]; then
      echo "\\par\\vspace{${ROWGAP_MM}mm}"
      echo "\\includegraphics[scale=$SCALE]{si_latent_${it}_b.pdf}"
    fi
    echo '\end{minipage}'
    echo '\end{document}'
  } > "$TEX"
  ( cd "$PANELS" && pdflatex -interaction=nonstopmode -halt-on-error "$(basename "$TEX")" > /dev/null ) \
    || { echo "pdflatex failed; see ${TEX%.tex}.log"; exit 1; }
  rm -f "${TEX%.tex}.aux" "${TEX%.tex}.log"
  echo "wrote ${TEX%.tex}.pdf: $(pdfinfo "${TEX%.tex}.pdf" | grep 'Page size')"
done
