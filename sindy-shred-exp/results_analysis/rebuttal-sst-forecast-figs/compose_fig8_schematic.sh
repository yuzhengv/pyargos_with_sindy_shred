#!/usr/bin/env bash
# Revised Fig. 8 (SINDy-SHRED integration schematic): overlay the latent model of
# the highlighted experiment (exp 91, posterior means rounded to two decimals,
# ../rebuttal-latent-models/results/exp_91/posterior_ba_deg1.csv) on the
# "Latent Dynamical System" box of the diagrams.net export
# schematic-plots/pyargos_with_sindy_shred.pdf (919.92 x 687.12 pt), which still
# shows the equations of the previously highlighted experiment 18.
#
# A standalone TikZ document includes the page unchanged, covers the three old
# equation lines with a rectangle in the box's own fill colour (rgb 237/238/250,
# sampled from the page rasterised at 150 dpi) and typesets the three new lines
# at the old baselines in sans-serif mathematics (helvet + sfmath), 14 pt, which
# matches the 10 pt digit height of the old Computer Modern lines; the minus
# sign is Helvetica's \textminus (textcomp), so that no Computer Modern symbol
# font is embedded. Coordinates
# are PDF points (bp) from the page's bottom-left corner, read from the raster:
# old lines at x 653-891, y 75-156; baselines 146.5, 113.4 and 77.9; the grey
# arrow entering the box ends at x = 649.5, so the rectangle starts at 652.
#
# Usage: ./compose_fig8_schematic.sh <schematic.pdf> <out.pdf>
#   e.g. ./compose_fig8_schematic.sh ../../../../../schematic-plots/pyargos_with_sindy_shred.pdf \
#                                    figures/house/sindy_shred_integration.pdf
set -euo pipefail
cd "$(dirname "$0")"
SRC="${1:?path to pyargos_with_sindy_shred.pdf}"
OUT="${2:-figures/house/sindy_shred_integration.pdf}"
SRC="$(realpath "$SRC")"
mkdir -p "$(dirname "$OUT")"
TEX="$(dirname "$OUT")/sindy_shred_integration.tex"

pdfinfo "$SRC" | grep -q "919.92 x 687.12" || { echo "unexpected page size; the overlay coordinates assume 919.92 x 687.12 pt"; exit 1; }

cat > "$TEX" <<TEX
% generated by compose_fig8_schematic.sh; do not edit by hand
\documentclass[border=0pt]{standalone}
\usepackage[T1]{fontenc}
\usepackage{textcomp}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{sfmath}
\newcommand{\mi}{\mathbin{\text{\textminus}}}
\newcommand{\mneg}{\text{\textminus}}
\usepackage{amsmath}
\usepackage{graphicx}
\usepackage{tikz}
\definecolor{boxfill}{RGB}{237,238,250}
\begin{document}
\begin{tikzpicture}[x=1bp, y=1bp, inner sep=0pt, outer sep=0pt]
\node[anchor=south west] at (0,0) {\includegraphics{$SRC}};
\fill[boxfill] (652,70) rectangle (894,161);
\begin{scope}[every node/.style={anchor=base west, font=\fontsize{14}{34}\selectfont}]
\node at (654.5,146.5) {\$\dot{z}_1 = \mneg 0.98 + 8.16\,z_2 \mi 4.20\,z_3\$};
\node at (654.5,113.4) {\$\dot{z}_2 = 0.55 \mi 3.41\,z_2 + 6.15\,z_3\$};
\node at (654.5,77.9)  {\$\dot{z}_3 = 0.95 \mi 8.19\,z_2 + 3.43\,z_3\$};
\end{scope}
\end{tikzpicture}
\end{document}
TEX

( cd "$(dirname "$TEX")" && pdflatex -interaction=nonstopmode -halt-on-error "$(basename "$TEX")" > /dev/null ) \
  || { echo "pdflatex failed; see ${TEX%.tex}.log"; exit 1; }
rm -f "${TEX%.tex}.aux" "${TEX%.tex}.log"
if [ "$(realpath -m "$OUT")" != "$(realpath -m "${TEX%.tex}.pdf")" ]; then cp "${TEX%.tex}.pdf" "$OUT"; fi
echo "wrote $OUT: $(pdfinfo "$OUT" | grep 'Page size')"
