#!/usr/bin/env bash
# Compose the revised Fig. 9 (sea-surface-temperature application) from the three
# house-style panels written by make_fig9_panels.py: a (left) and b (right) on the
# top row, c full width below. Each panel is included at scale 0.4 = 1/2.5 of its
# canvas, so the text sizes set in plot-style/house.mplstyle come out at final
# size; the page is a 183 mm wide box plus a 1 mm border on every side, so that
# \includegraphics[width=\textwidth] in the manuscript shows the figure at 183 mm.
# Usage: ./compose_fig9.sh [out.pdf]   (default: figures/house/sst_application.pdf)
# Requires pdflatex with standalone, graphicx and helvet (TeX Live 2023).
set -euo pipefail
cd "$(dirname "$0")"
OUT="${1:-figures/house/sst_application.pdf}"
PANELS=figures/house
TEX=figures/house/sst_application.tex
SCALE=0.4
WIDTH_MM=183
GUTTER_MM=0      # between a and b: their canvases (8.3 + 9.7 in) already fill the box
ROWGAP_MM=2      # between the top row and c

width_pt() { pdfinfo "$1" | awk '/Page size/ {print $3}'; }
for p in a b c; do
  test -f "$PANELS/fig9$p.pdf" || { echo "missing $PANELS/fig9$p.pdf (run make_fig9_panels.py)"; exit 1; }
done
wa=$(width_pt $PANELS/fig9a.pdf); wb=$(width_pt $PANELS/fig9b.pdf); wc=$(width_pt $PANELS/fig9c.pdf)
row_mm=$(awk -v a="$wa" -v b="$wb" -v s="$SCALE" 'BEGIN {printf "%.2f", (a + b) * s * 25.4 / 72}')
c_mm=$(awk -v c="$wc" -v s="$SCALE" 'BEGIN {printf "%.2f", c * s * 25.4 / 72}')
echo "top row (a + b) at scale $SCALE: $row_mm mm; c: $c_mm mm; box: $WIDTH_MM mm"
awk -v r="$row_mm" -v c="$c_mm" -v w="$WIDTH_MM" -v g="$GUTTER_MM" 'BEGIN {
  if (r + g > w + 0.2 || c > w + 0.2) { print "panels wider than the box: shrink the canvases"; exit 1 } }'

cat > "$TEX" <<TEX
% generated by compose_fig9.sh; do not edit by hand
\documentclass[border=1mm]{standalone}
\usepackage[T1]{fontenc}
\usepackage{helvet}
\renewcommand{\familydefault}{\sfdefault}
\usepackage{graphicx}
\begin{document}
\begin{minipage}[t]{${WIDTH_MM}mm}
\setlength{\parindent}{0pt}\setlength{\parskip}{0pt}
\begin{minipage}[t]{\dimexpr${WIDTH_MM}mm-${GUTTER_MM}mm-$(awk -v b="$wb" -v s="$SCALE" 'BEGIN {printf "%.3f", b * s}')pt\relax}
\vspace{0pt}\includegraphics[scale=$SCALE]{fig9a.pdf}
\end{minipage}\hfill
\begin{minipage}[t]{$(awk -v b="$wb" -v s="$SCALE" 'BEGIN {printf "%.3f", b * s}')pt}
\vspace{0pt}\includegraphics[scale=$SCALE]{fig9b.pdf}
\end{minipage}\par
\vspace{${ROWGAP_MM}mm}
\includegraphics[scale=$SCALE]{fig9c.pdf}
\end{minipage}
\end{document}
TEX

( cd "$(dirname "$TEX")" && pdflatex -interaction=nonstopmode -halt-on-error "$(basename "$TEX")" > /dev/null ) \
  || { echo "pdflatex failed; see ${TEX%.tex}.log"; exit 1; }
rm -f "${TEX%.tex}.aux" "${TEX%.tex}.log"
if [ "$(realpath -m "$OUT")" != "$(realpath -m "${TEX%.tex}.pdf")" ]; then cp "${TEX%.tex}.pdf" "$OUT"; fi
echo "wrote $OUT: $(pdfinfo "$OUT" | grep 'Page size')"
